import math

import torch

from quic_wc import QuICWCConfig, QuICWCLinear, SideConfig
from quic_wc.distillation import FitConfig, fit


def anisotropic_second_moment(n, seed):
    g = torch.Generator().manual_seed(seed)
    mix = torch.randn(n, n, generator=g) * torch.logspace(0, -1, n)
    return mix @ mix.T / n + 0.05 * torch.eye(n)


def small_config(**changes):
    base = dict(in_features=20, out_features=30, rank=8,
                left=SideConfig(base_size=4, num_stages=2, permutation="stride"),
                right=SideConfig(base_size=4, num_stages=2, permutation="stride"))
    base.update(changes)
    return QuICWCConfig(**base)


def test_positive_control_recovers_teacher_from_same_family():
    """A teacher generated by the same parametrisation must be learnable from identity init."""
    torch.manual_seed(0)
    cfg = small_config()
    sigma = torch.linspace(3.0, 0.5, 8)
    teacher = QuICWCLinear(cfg, sigma)
    with torch.no_grad():
        teacher.left.theta.normal_(0, 0.3)
        teacher.right.theta.normal_(0, 0.3)
        w_teacher = teacher.reconstruct_weight()
    student = QuICWCLinear(cfg, sigma)
    c = anisotropic_second_moment(20, 1)
    result = fit(student, w_teacher, c, c_val=anisotropic_second_moment(20, 2),
                 cfg=FitConfig(steps=1500, lr=2e-2, eval_every=100))
    assert result.status == "completed"
    assert result.history[0]["val_rel_mse"] > 0.5
    assert result.best_val_rel_mse < 1e-2, result.best_val_rel_mse


def test_nonfinite_loss_stops_before_optimizer_step():
    cfg = small_config()
    student = QuICWCLinear(cfg, torch.ones(8))
    c = anisotropic_second_moment(20, 3)
    c[0, 0] = math.nan
    before = student.left.theta.detach().clone()
    result = fit(student, torch.randn(30, 20), c, cfg=FitConfig(steps=5, restore_best=False))
    assert result.status.startswith("nonfinite") and result.steps_completed == 0
    assert torch.equal(student.left.theta.detach(), before)


def test_restore_best_and_history_contract():
    torch.manual_seed(1)
    cfg = small_config(sigma_mode="learnable")
    w = torch.randn(30, 20)
    student = QuICWCLinear(cfg, torch.linalg.svdvals(w)[:8])
    result = fit(student, w, anisotropic_second_moment(20, 4), cfg=FitConfig(steps=200, lr=1e-2, eval_every=50))
    assert [h["step"] for h in result.history] == [0, 50, 100, 150, 200]
    best = min(h["val_rel_mse"] for h in result.history)
    assert math.isclose(result.best_val_rel_mse, best)
    assert result.best_val_rel_mse <= result.history[0]["val_rel_mse"]
